`timescale 1ns / 1ps

module ALU_tb();

// Inputs
reg [3:0] A;
reg [3:0] B;
reg [1:0] op;

// Outputs
wire [3:0] res;
wire Cout;

// Instantiate the Unit Under Test (UUT)
ALU uut (
    .A(A),
    .B(B),
    .op(op),
    .res(res),
    .Cout(Cout)
);

initial begin
    // 初始化
    A = 0; B = 0; op = 0;

    // =====================
    // ADD 测试 (op = 00)
    // =====================
    op = 2'b00;

    // 普通情况
    A = 4'b0011; B = 4'b0101; #10; // 3 + 5 = 8

    // 边界：溢出
    A = 4'b1111; B = 4'b0001; #10; // 15 + 1 = 16 (Cout=1)

    // =====================
    // SUB 测试 (op = 01)
    // =====================
    op = 2'b01;

    // 普通情况
    A = 4'b1000; B = 4'b0011; #10; // 8 - 3 = 5

    // 边界：借位
    A = 4'b0000; B = 4'b0001; #10; // 0 - 1

    // =====================
    // AND 测试 (op = 10)
    // =====================
    op = 2'b10;

    // 普通情况
    A = 4'b1100; B = 4'b1010; #10;

    // 全0测试
    A = 4'b0000; B = 4'b1111; #10;

    // =====================
    // OR 测试 (op = 11)
    // =====================
    op = 2'b11;

    // 普通情况
    A = 4'b1100; B = 4'b0011; #10;

    // 全1测试
    A = 4'b0000; B = 4'b1111; #10;

    // 结束仿真
    $stop;
end

endmodule